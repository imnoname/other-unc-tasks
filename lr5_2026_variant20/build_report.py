heading('2.4 Качество движения макропеременной и уравнение Эйлера–Лагранжа',2)
para('В теоретической части методических указаний рассматривается функционал качества, штрафующий отклонение макропеременной от целевого множества и скорость её изменения. Для непрерывного времени соответствующая запись имеет вид J=∫[ψ²+ω(dψ/dt)²]dt, где ω>0 задаёт относительный вес скорости. При варьировании траектории ψ условие стационарности даёт уравнение Эйлера–Лагранжа:')
